// The generated dataset lives in a git-ignored path (redacted real-session
// transcripts, too large/privacy-sensitive to commit), so it is loaded at
// runtime; types come from the committed context-dataset-types.ts module.
let F9_CONTEXT_DATASET: readonly F9ContextItem[] = [];

async function loadContextDataset(): Promise<boolean> {
	const datasetPath = join("docs", "internal", "context-dataset.draft.ts");
	try {
		// SAFETY: the draft module is generated by collect-corpus.ts with exactly this
		// export shape; the cast only attaches the committed contract type.
		const module = (await import(pathToFileURL(datasetPath).href)) as {
			F9_CONTEXT_DATASET?: readonly F9ContextItem[];
		};
		if (module.F9_CONTEXT_DATASET === undefined || module.F9_CONTEXT_DATASET.length === 0) {
			console.error(
				`[ctx] ${datasetPath} exported no F9_CONTEXT_DATASET. Regenerate it with:\n` +
					"  bun scripts/f9-experiment/collect-corpus.ts --budget 20000 --max-items 12",
			);
			return false;
		}
		F9_CONTEXT_DATASET = module.F9_CONTEXT_DATASET;
		return true;
	} catch {
		console.error(
			`[ctx] dataset not found at ${datasetPath} (git-ignored; real-session transcripts must not be committed). Regenerate it with:\n` +
				"  bun scripts/f9-experiment/collect-corpus.ts --budget 20000 --max-items 12",
		);
		return false;
	}
}

const REVIEW_TOKEN_CEILING = 1_000_000;
const COST_CEILING_USD = 25;

// Per-run results are appended to a JSONL sidecar so an interrupted run can
// resume without re-spending completed (item, arm) pairs.
const RESULTS_PATH = join("docs", "internal", "context-results.jsonl");

type ContextArm = "with-reasoning" | "no-reasoning";

/** Aggregate evaluation note payload written at the end of a context run. */
interface ContextEvaluation {
	modelReference: string;
	responseModels: Set<string>;
	results: readonly ContextRunResult[];
	summaries: ReturnType<typeof summarizeContext>[];
	stoppedEarly: boolean;
	reason?: string;
}

interface ContextRunResult {
	itemId: string;
	arm: ContextArm;
	note?: string;
	severity?: string;
	truncated?: boolean;
	stopReason: string;
	errorMessage?: string;
	verdict: "hit" | "miss" | "false-positive" | "silence-correct" | "run-error";
	tokens: number;
	costUsd: number;
	responseModel?: string;
	renderedBytes: number;
	retainedEntries: number;
	totalEntries: number;
}

function renderItemDelta(item: F9ContextItem, includeReasoning: boolean): string {
	return renderAdvisorDelta(item.entries, item.budgetTokens, { includeReasoning }).text;
}

function verdictFor(note: string | undefined, item: F9ContextItem): ContextRunResult["verdict"] {
	const expectation = item.expectation;
	if (expectation.kind === "silence") {
		return note === undefined ? "silence-correct" : "false-positive";
	}
	if (note === undefined) return "miss";
	const normalized = note.toLocaleLowerCase("en-US");
	return expectation.terms.some((term) => normalized.includes(term.toLocaleLowerCase("en-US")))
		? "hit"
		: "miss";
}

interface ArmUsage {
	tokens: number;
	costUsd: number;
	responseModel?: string;
}

function lastAssistantUsage(session: AgentSession): ArmUsage {
	for (let index = session.messages.length - 1; index >= 0; index--) {
		const message = session.messages[index];
		if (message?.role !== "assistant") continue;
		const assistant = message;
		if (assistant.stopReason === "aborted" || assistant.stopReason === "error") continue;
		const tokens = calculateContextTokens(assistant.usage);
		const usage: ArmUsage = {
			tokens,
			costUsd: assistant.usage.cost.total,
		};
		if (assistant.responseModel !== undefined) usage.responseModel = assistant.responseModel;
		else if (assistant.model.length > 0) usage.responseModel = assistant.model;
		return usage;
	}
	return { tokens: 0, costUsd: 0 };
}

async function runContextArm(options: {
	cwd: string;
	agentDir: string;
	modelRuntime: ModelRuntime;
	model: Model<string>;
	prompt: string;
	item: F9ContextItem;
	arm: ContextArm;
}): Promise<ContextRunResult> {
	const collector: AdviceCollector = {
		validCalls: 0,
		suppressedCalls: 0,
		memoryPolicySuppressedCalls: 0,
		memoryLimitSuppressedCalls: 0,
	};
	const config = structuredClone(DEFAULT_ADVISOR_CONFIG);
	config.model = `${options.model.provider}/${options.model.id}`;
	config.limits.sessionTokenSoftCap = REVIEW_TOKEN_CEILING;
	config.limits.sessionCostSoftCapUsd = COST_CEILING_USD;
	const settingsManager = SettingsManager.inMemory({
		compaction: { enabled: false },
		retry: { enabled: false },
	});
	const resourceLoader = new DefaultResourceLoader({
		cwd: options.cwd,
		agentDir: options.agentDir,
		settingsManager,
		noExtensions: true,
		noSkills: true,
		noPromptTemplates: true,
		noThemes: true,
		noContextFiles: true,
		systemPromptOverride: () => options.prompt,
		appendSystemPromptOverride: () => [],
	});
	await resourceLoader.reload();
	const sessionManager = SessionManager.inMemory(options.cwd);
	const { session } = await createAgentSession({
		cwd: options.cwd,
		agentDir: options.agentDir,
		modelRuntime: options.modelRuntime,
		model: options.model,
		thinkingLevel: "off",
		resourceLoader,
		sessionManager,
		settingsManager,
		customTools: [createAdviseTool(config, collector)],
		tools: ["advise"],
	});
	try {
		const delta = renderItemDelta(options.item, options.arm === "with-reasoning");
		const retained = renderAdvisorDelta(options.item.entries, options.item.budgetTokens, {
			includeReasoning: options.arm === "with-reasoning",
		}).retainedEntryCount;
		await session.prompt(`<advisor-update>\n${delta}\n</advisor-update>`, {
			expandPromptTemplates: false,
			source: "extension",
		});
		const usage = lastAssistantUsage(session);
		const accepted = collector.accepted;
		const last = session.messages.at(-1);
		const lastAssistant = last?.role === "assistant" ? last : undefined;
		if (
			lastAssistant !== undefined &&
			(lastAssistant.stopReason === "error" || lastAssistant.stopReason === "aborted")
		) {
			return {
				itemId: options.item.id,
				arm: options.arm,
				stopReason: lastAssistant.stopReason,
				errorMessage: lastAssistant.errorMessage ?? "provider request failed",
				verdict: "run-error" as const,
				tokens: 0,
				costUsd: 0,
				renderedBytes: Buffer.byteLength(delta, "utf8"),
				retainedEntries: retained,
				totalEntries: options.item.entries.length,
			};
		}
		const result: ContextRunResult = {
			itemId: options.item.id,
			arm: options.arm,
			stopReason: lastAssistant?.stopReason ?? "unknown",
			verdict: verdictFor(accepted?.note, options.item),
			tokens: usage.tokens,
			costUsd: usage.costUsd,
			renderedBytes: Buffer.byteLength(delta, "utf8"),
			retainedEntries: retained,
			totalEntries: options.item.entries.length,
		};
		if (accepted !== undefined) {
			result.note = accepted.note;
			result.truncated = accepted.truncated;
		}
		if (accepted?.intent === "review") result.severity = accepted.severity;
		if (usage.responseModel !== undefined) result.responseModel = usage.responseModel;
		return result;
	} finally {
		session.dispose();
	}
}

function summarizeContext(results: readonly ContextRunResult[], arm: ContextArm) {
	const armResults = results.filter((result) => result.arm === arm);
	const labeled = armResults.filter((result) => result.verdict !== "run-error");
	const silenceItems = labeled.filter(
		(result) =>
			F9_CONTEXT_DATASET.find((item) => item.id === result.itemId)?.expectation.kind === "silence",
	);
	const silenceCorrect = silenceItems.filter(
		(result) => result.verdict === "silence-correct",
	).length;
	const falsePositives = silenceItems.filter(
		(result) => result.verdict === "false-positive",
	).length;
	const findingItems = labeled.filter(
		(result) =>
			F9_CONTEXT_DATASET.find((item) => item.id === result.itemId)?.expectation.kind === "finding",
	);
	const hits = findingItems.filter((result) => result.verdict === "hit").length;
	const tokens = armResults.reduce((sum, result) => sum + result.tokens, 0);
	const costUsd = armResults.reduce((sum, result) => sum + result.costUsd, 0);
	const avgRetained = armResults.reduce((sum, result) => sum + result.retainedEntries, 0);
	const avgRenderedBytes = armResults.reduce((sum, result) => sum + result.renderedBytes, 0);
	const n = armResults.length;
	return {
		arm,
		items: armResults.length,
		silenceCorrect,
		silenceItems: silenceItems.length,
		silenceCorrectRate: silenceItems.length === 0 ? 0 : silenceCorrect / silenceItems.length,
		falsePositives,
		falsePositiveRate: silenceItems.length === 0 ? 0 : falsePositives / silenceItems.length,
		hits,
		findingItems: findingItems.length,
		findingHitRate: findingItems.length === 0 ? 0 : hits / findingItems.length,
		tokens,
		costUsd,
		avgRetainedEntries: n === 0 ? 0 : avgRetained / n,
		avgRenderedBytes: n === 0 ? 0 : avgRenderedBytes / n,
	};
}

async function writeContextEvaluationNote(options: {
	modelReference: string;
	responseModels: Set<string>;
	results: readonly ContextRunResult[];
	summaries: ReturnType<typeof summarizeContext>[];
	stoppedEarly: boolean;
	reason?: string;
}): Promise<string> {
	const { results, summaries } = options;
	const rows = results
		.map((result) => {
			const item = F9_CONTEXT_DATASET.find((entry) => entry.id === result.itemId);
			const expectation = item?.expectation;
			const expected =
				expectation === undefined
					? "unlabeled"
					: expectation.kind === "finding"
						? expectation.terms.join(", ")
						: "silence";
			const detail =
				result.verdict === "run-error"
					? `run error: ${result.errorMessage ?? result.stopReason}`
					: (result.note ?? "(silence)").replaceAll("\n", " ");
			return `| ${result.itemId} | ${result.arm} | ${String(result.retainedEntries)} | ${result.verdict} | ${expected.replaceAll("|", "\\|")} | ${detail.slice(0, 140).replaceAll("|", "\\|")} |`;
		})
		.join("\n");
	const summary = summaries
		.map(
			(summary) =>
				`| ${summary.arm} | ${String(summary.silenceCorrect)}/${String(summary.silenceItems)} | ${(summary.silenceCorrectRate * 100).toFixed(1)}% | ${(summary.falsePositiveRate * 100).toFixed(1)}% | ${String(summary.hits)}/${String(summary.findingItems)} | ${(summary.findingHitRate * 100).toFixed(1)}% | ${summary.avgRetainedEntries.toFixed(1)} | ${summary.avgRenderedBytes.toFixed(0)} | ${String(summary.tokens)} | $${summary.costUsd.toFixed(4)} |`,
		)
		.join("\n");
	const totalTokens = summaries.reduce((sum, summary) => sum + summary.tokens, 0);
	const totalCost = summaries.reduce((sum, summary) => sum + summary.costUsd, 0);
	const note = `# Context-composition experiment evaluation note

Status: ${options.stoppedEarly ? `stopped early: ${options.reason ?? "budget ceiling reached"}` : "completed"}.
Draft protocol; mechanism analysis, not a shipping decision. This experiment never changes default behavior.

## Hypothesis

Removing reasoning blocks (and freeing the token budget for more Executor
history) changes Advisor detection accuracy on updates that would otherwise be
truncated by \`context.maxUpdateTokens\`.

## Protocol

- Dataset: ${String(F9_CONTEXT_DATASET.length)} real-session cuts in \`docs/internal/context-dataset.draft.ts\` (expectation labels reviewed; every cut triggers the \`renderBoundedEntries\` truncation branch at its \`budgetTokens\`).
- Arms: \`with-reasoning\` (production rendering, includeReasoning=true) vs \`no-reasoning\` (includeReasoning=false), same budget and same dataset; both rendered through \`renderAdvisorDelta\`.
- Metrics: note quality (expected terms), false-positive rate, silence correctness, retained Executor entries per arm.
- Budget ceilings: ${String(REVIEW_TOKEN_CEILING)} review tokens and $${String(COST_CEILING_USD)}, enforced via the same soft-cap fields as F9.
- Live-model runs only; provider extension opt-in via \`PI_ADVISOR_EXPERIMENT_PROVIDER_EXTENSION\`.

## Model identity

Configured model: \`${options.modelReference}\`.
Provider-reported response models: ${[...options.responseModels].join(", ") || "(none recorded)"}.

## Aggregate results

| Arm | Silence correct | Silence-correct rate | False-positive rate | Finding hits | Finding-hit rate | Avg retained entries | Avg rendered bytes | Tokens | Cost |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${summary}

Total: ${String(totalTokens)} tokens, $${totalCost.toFixed(4)}.

## Per-run results

| Item | Arm | Retained entries | Verdict | Expected | Note (truncated) |
| --- | --- | --- | --- | --- | --- |
${rows}

## Reading

- If \`no-reasoning\` shows a higher retained-entry count (more Executor history in the window) and a non-worse hit rate, the mechanism holds: reasoning was displacing history without adding detection value.
- A drop in finding-hit rate on \`no-reasoning\` would indicate reasoning carries material signal for these cuts.
- A single run is subject to model variance; treat any delta as a signal to measure, not a conclusion. Multiple runs or a larger dataset are required before a decision.
`;
	const path = join("docs", "internal", "context-evaluation.md");
	await mkdir(dirname(path), { recursive: true });
	await writeFile(path, note, "utf8");
	return path;
}

async function registerUserProviderExtensions(
	agentDir: string,
	providerId: string,
	modelRuntime: ModelRuntime,
): Promise<string[]> {
	if (process.env.PI_ADVISOR_EXPERIMENT_PROVIDER_EXTENSION !== providerId) {
		console.warn(
			`[ctx] the configured provider ${providerId} is not available from the built-in runtime. Set PI_ADVISOR_EXPERIMENT_PROVIDER_EXTENSION=${providerId} to load its extension from ${join(agentDir, "extensions", providerId)} after reviewing the extension source.`,
		);
		return [];
	}
	if (!/^[a-z0-9][a-z0-9_-]*$/iu.test(providerId)) {
		console.warn(
			`[ctx] refusing to load a provider extension for unsafe provider id ${JSON.stringify(providerId)}`,
		);
		return [];
	}
	const extensionsDir = join(agentDir, "extensions");
	const entryPath = join(extensionsDir, providerId, "index.ts");
	if (!entryPath.startsWith(`${extensionsDir}${sep}`)) return [];
	try {
		interface ProviderRegistrationApi {
			registerProvider(
				registeredProviderId: string,
				config: Parameters<ModelRuntime["registerProvider"]>[1],
			): void;
			registerCommand(): void;
			on(): void;
		}
		// SAFETY: dynamic provider modules are validated for a callable default before execution.
		const module = (await import(pathToFileURL(entryPath).href)) as {
			default?: (pi: ProviderRegistrationApi) => Promise<void> | void;
		};
		if (!isFunctionValue(module.default)) return [];
		console.warn(
			`[ctx] executing user extension ${providerId} outside Pi's extension loading path to resolve the configured provider. Review the extension source before running this experiment.`,
		);
		const adapter: ProviderRegistrationApi = {
			registerProvider: (
				registeredProviderId: string,
				config: Parameters<ModelRuntime["registerProvider"]>[1],
			) => {
				modelRuntime.registerProvider(registeredProviderId, config);
			},
			registerCommand: () => undefined,
			on: () => undefined,
		};
		await Promise.resolve(module.default(adapter));
		return [providerId];
	} catch (error) {
		console.warn(
			`[ctx] provider extension ${providerId} could not load: ${error instanceof Error ? error.message : String(error)}`,
		);
		return [];
	}
}

async function loadPersistedResults(): Promise<ContextRunResult[]> {
	try {
		const raw = await readFile(RESULTS_PATH, "utf8");
		return raw
			.split("\n")
			.filter((line) => line.trim().length > 0)
			.map((line) => {
				// SAFETY: this JSONL was written by this harness with ContextRunResult records;
				// a malformed line throws into the catch below and resumes from an empty set.
				return JSON.parse(line) as ContextRunResult;
			});
	} catch {
		return [];
	}
}

async function main(): Promise<void> {
	if (!(await loadContextDataset())) {
		process.exitCode = 1;
		return;
	}
	const persisted = await loadPersistedResults();
	if (persisted.length > 0) {
		console.log(
			`[ctx] resuming: ${String(persisted.length)} results already recorded in ${RESULTS_PATH}`,
		);
	}
	const knownExpectationKinds: ReadonlySet<string> = new Set(["silence", "finding"]);
	const labeled = F9_CONTEXT_DATASET.filter((item) =>
		knownExpectationKinds.has(item.expectation.kind),
	);
	if (labeled.length !== F9_CONTEXT_DATASET.length) {
		console.error(
			`[ctx] dataset has ${String(labeled.length)}/${String(F9_CONTEXT_DATASET.length)} labeled items; label all expectations before running.`,
		);
		process.exitCode = 1;
		return;
	}
	const agentDir = getAgentDir();
	const cwd = process.cwd();
	const loaded = await loadAdvisorConfiguration({
		agentDir,
		cwd,
		projectTrusted: false,
		fallbackUserConfig: DEFAULT_ADVISOR_CONFIG,
	});
	const modelReference = loaded.effectiveConfig.model;
	if (modelReference === undefined) {
		console.error(
			"[ctx] requires a configured Advisor model in the User WATCHDOG configuration. The experiment was not run.",
		);
		process.exitCode = 1;
		return;
	}
	const separator = modelReference.indexOf("/");
	const providerId = separator < 0 ? modelReference : modelReference.slice(0, separator);
	const modelId = separator < 0 ? modelReference : modelReference.slice(separator + 1);

	const modelRuntime = await ModelRuntime.create({
		authPath: join(agentDir, "auth.json"),
		modelsPath: join(agentDir, "models.json"),
		allowModelNetwork: true,
	});
	const registry = new ModelRegistry(modelRuntime);
	let available = registry.getAvailable();
	if (!available.some((model) => `${model.provider}/${model.id}` === modelReference)) {
		const loadedExtensions = await registerUserProviderExtensions(
			agentDir,
			providerId,
			modelRuntime,
		);
		if (loadedExtensions.length > 0) {
			console.log(`[ctx] loaded provider extension: ${loadedExtensions.join(", ")}`);
			await registry.refresh();
			available = registry.getAvailable();
		}
	}
	if (!available.some((model) => `${model.provider}/${model.id}` === modelReference)) {
		console.error(
			`[ctx] could not resolve an authenticated model for ${modelReference}. The experiment was not run.`,
		);
		process.exitCode = 1;
		return;
	}
	const model = modelRuntime.getModel(providerId, modelId);
	if (model === undefined) {
		console.error(`[ctx] could not find model ${modelReference}. The experiment was not run.`);
		process.exitCode = 1;
		return;
	}

	const prompt = buildAdvisorSystemPrompt(loaded.effectiveConfig, "");
	const results: ContextRunResult[] = [...persisted];
	const donePairs = new Set(persisted.map((result) => `${result.itemId}:${result.arm}`));
	const responseModels = new Set<string>(
		persisted.flatMap((result) =>
			result.responseModel === undefined ? [] : [result.responseModel],
		),
	);
	let totalTokens = 0;
	let totalCostUsd = 0;
	let stoppedEarly = false;
	let stopReason: string | undefined;
	let consecutiveErrors = 0;
	for (const item of labeled) {
		for (const arm of ["with-reasoning", "no-reasoning"] as const) {
			if (donePairs.has(`${item.id}:${arm}`)) {
				console.log(`[ctx] ${item.id} ${arm} (already recorded, skipping)`);
				continue;
			}
			console.log(`[ctx] ${item.id} ${arm}`);
			try {
				const result = await runContextArm({
					cwd,
					agentDir,
					modelRuntime,
					model,
					prompt,
					item,
					arm,
				});
				results.push(result);
				await appendFile(RESULTS_PATH, `${JSON.stringify(result)}\n`, "utf8");
				if (result.verdict === "run-error") {
					consecutiveErrors++;
					console.error(`  -> run error: ${result.errorMessage ?? result.stopReason}`);
					if (consecutiveErrors >= 3) {
						stoppedEarly = true;
						stopReason = `provider request failed 3 times in a row (last: ${result.errorMessage ?? result.stopReason}); upstream availability or rate limits`;
						break;
					}
				} else {
					consecutiveErrors = 0;
					totalTokens += result.tokens;
					totalCostUsd += result.costUsd;
					if (result.responseModel !== undefined) responseModels.add(result.responseModel);
					console.log(
						`  -> ${result.verdict} (retained ${String(result.retainedEntries)}/${String(result.totalEntries)})${result.note === undefined ? "" : `: ${result.note.slice(0, 120)}`} (${String(result.tokens)} tokens, $${result.costUsd.toFixed(4)})`,
					);
				}
			} catch (error) {
				const failed: ContextRunResult = {
					itemId: item.id,
					arm,
					stopReason: "thrown",
					errorMessage: error instanceof Error ? error.message : String(error),
					verdict: "run-error",
					tokens: 0,
					costUsd: 0,
					renderedBytes: 0,
					retainedEntries: 0,
					totalEntries: item.entries.length,
				};
				results.push(failed);
				await appendFile(RESULTS_PATH, `${JSON.stringify(failed)}\n`, "utf8");
				consecutiveErrors++;
				console.error(`  -> run error: ${error instanceof Error ? error.message : String(error)}`);
				if (consecutiveErrors >= 3) {
					stoppedEarly = true;
					stopReason = `provider request failed 3 times in a row (last: ${error instanceof Error ? error.message : String(error)}); upstream availability or rate limits`;
					break;
				}
			}
			if (totalTokens >= REVIEW_TOKEN_CEILING || totalCostUsd >= COST_CEILING_USD) {
				stoppedEarly = true;
				stopReason = `budget ceiling reached at ${String(totalTokens)} tokens / $${totalCostUsd.toFixed(4)}`;
				break;
			}
		}
		if (stoppedEarly) break;
	}
	const summaries = [
		summarizeContext(results, "with-reasoning"),
		summarizeContext(results, "no-reasoning"),
	];
	const evaluation: ContextEvaluation = {
		modelReference,
		responseModels,
		results,
		summaries,
		stoppedEarly,
	};
	if (stopReason !== undefined) evaluation.reason = stopReason;
	const path = await writeContextEvaluationNote(evaluation);
	console.log("");
	for (const summary of summaries) {
		console.log(
			`[ctx] ${summary.arm}: silence ${String(summary.silenceCorrect)}/${String(summary.silenceItems)} (fp ${(summary.falsePositiveRate * 100).toFixed(1)}%), findings ${String(summary.hits)}/${String(summary.findingItems)} (${(summary.findingHitRate * 100).toFixed(1)}%), avg retained ${summary.avgRetainedEntries.toFixed(1)}, ${String(summary.tokens)} tokens, $${summary.costUsd.toFixed(4)}`,
		);
	}
	console.log(`[ctx] evaluation note written to ${path}`);
	if (stoppedEarly) console.log(`[ctx] ${stopReason ?? "stopped early"}`);
}

await main();
