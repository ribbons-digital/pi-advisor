/**
 * Context-composition experiment harness (protocol draft 2026-09-02).
 *
 * A/B test of the hypothesis: "stripping reasoning (and per-turn tool-result
 * bodies) from the bounded Advisor update, and using the freed budget for more
 * Executor history, changes detection accuracy."
 *
 * Arms (all render through the production `renderAdvisorDelta`):
 *   - `with-reasoning`:    includeReasoning=true, budget=item.budgetTokens
 *   - `no-reasoning`:      includeReasoning=false, budget=item.budgetTokens
 *   - `no-reasoning-more`: includeReasoning=false, budget=item.budgetTokens
 *                          (same input; the extra retained history is what the
 *                           freed budget buys — measured via
 *                           retainedEntryCount)
 *
 * For each cut, the rendered delta is wrapped the same way the runtime wraps
 * it (`<advisor-update>` + project-context omitted here; the experiment runs
 * with an empty project context, mirroring F9). Metrics: note quality
 * (expected terms), false-positive rate, silence correctness, and the number
 * of retained Executor entries each arm sees.
 *
 * Budget ceilings: 1,000,000 review tokens and $25, enforced through the same
 * soft-cap fields as F9. Live model required; provider extension opt-in via
 * `PI_ADVISOR_EXPERIMENT_PROVIDER_EXTENSION=<providerId>` (same as F9).
 *
 * Run: `pnpm experiment:context`
 */
